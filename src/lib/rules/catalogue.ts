export type IssueGroup = "must" | "should" | "nice";

// The brief's three buckets. Critical failures block people outright; serious
// ones make tasks very hard; moderate and minor ones add friction.
export function groupForImpact(impact: Impact): IssueGroup {
  if (impact === "critical") return "must";
  if (impact === "serious") return "should";
  return "nice";
}

export const GROUP_LABEL: Record<IssueGroup, string> = {
  must: "Must fix",
  should: "Should fix",
  nice: "Nice to have",
};

export const IMPACT_WEIGHT: Record<Impact, number> = { critical: 10, serious: 7, moderate: 3, minor: 1 };

export const IMPACT_ORDER: Impact[] = ["critical", "serious", "moderate", "minor"];
